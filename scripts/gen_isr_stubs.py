#!/usr/bin/env python3
# gen_isr_stubs.py — generate isr_stubs.S: one stub per vector plus an
# explicit pointer table (no runtime pointer arithmetic).
# Copyright (c) Faded Dream OS Project. All rights reserved.
# Source is viewable but may not be copied, modified, or redistributed
# without permission.
#
# Vectors 0..31 are exceptions; 32..255 IRQs. Vectors where the CPU
# pushes an error code (8 10 11 12 13 14 17 21 29 30) skip the dummy
# push so the frame layout stays uniform.

ERRCODE_VECS = {8, 10, 11, 12, 13, 14, 17, 21, 29, 30}

def stub(vec):
    has_err = vec in ERRCODE_VECS
    lines = [f"isr_stub_{vec}:"]
    if not has_err:
        lines.append("    pushq $0")
    lines.append(f"    pushq ${vec}")
    for r in ("r15","r14","r13","r12","r11","r10","r9","r8",
              "rdi","rsi","rbp","rbx","rdx","rcx","rax"):
        lines.append(f"    pushq %{r}")
    lines.append("    movq %rsp, %rdi")
    lines.append("    call isr_dispatcher" if vec < 32
                 else "    call irq_dispatcher")
    for r in ("rax","rcx","rdx","rbx","rbp","rsi","rdi",
              "r8","r9","r10","r11","r12","r13","r14","r15"):
        lines.append(f"    popq %{r}")
    lines.append("    addq $16, %rsp")
    lines.append("    iretq")
    return "\n".join(lines) + "\n"

out = []
out.append("""/* isr_stubs.S — generated by scripts/gen_isr_stubs.py; do not edit.
 * Copyright (c) Faded Dream OS Project. All rights reserved.
 * Source is viewable but may not be copied, modified, or redistributed
 * without permission.
 */

.section .text
""")
for v in range(256):
    out.append(stub(v))

out.append("""
/* Explicit pointer table: idt.c installs gate N from isr_stub_table[N]. */
.section .rodata
.global isr_stub_table
isr_stub_table:
""")
for v in range(256):
    out.append(f"    .quad isr_stub_{v}\n")

import sys
open(sys.argv[1], "w").write("".join(out))
print(f"wrote {sys.argv[1]}: 256 stubs + pointer table")
