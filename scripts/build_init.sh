# Plain C, freestanding, position-fixed at 0x400000, embedded into the
# kernel image as rodata blobs (init_blob.S) so the kernel can copy
# them into fresh user pages. Two programs: init (the demo) and
# fault_init (privileged-instruction fault test).

set -eu
cd "$(dirname "$0")/.."

CC="${CC:-gcc}"
mkdir -p build

build_one() {
    local src=$1 prefix=$2
    $CC -std=c17 -Wall -Wextra -ffreestanding -nostdlib -fno-stack-protector \
        -fno-pic -fno-pie -mno-red-zone -mgeneral-regs-only \
        -mcmodel=small -O2 -m64 -c "$src" -o "build/${prefix}_user.o"

    ld -m elf_x86_64 -T user/init.ld -nostdlib -static \
        -o "build/${prefix}.elf" "build/${prefix}_user.o"

    objcopy -O binary "build/${prefix}.elf" "build/${prefix}.bin"

    local SIZE ENTRY SPAN
    SIZE=$(stat -c%s "build/${prefix}.bin")
    ENTRY=$(readelf -hW "build/${prefix}.elf" | awk '/Entry point/ {print $4}')
    SPAN=$(nm "build/${prefix}.elf" | awk '$3=="_end"{print "0x"$1}')

    {
        printf '.section .rodata\n'
        printf '.align 16\n'
        printf '.global %s_blob\n' "$prefix"
        printf '%s_blob:\n' "$prefix"
        printf '.incbin "build/%s.bin"\n' "$prefix"
        printf '.align 8\n'
        printf '.global %s_blob_size\n' "$prefix"
        printf '%s_blob_size:\n' "$prefix"
        printf '.quad %s\n' "$SIZE"
        printf '.global %s_blob_entry\n' "$prefix"
        printf '%s_blob_entry:\n' "$prefix"
        printf '.quad %s\n' "$ENTRY"
        printf '.global %s_blob_span\n' "$prefix"
        printf '%s_blob_span:\n' "$prefix"
        printf '.quad %s\n' "$SPAN"
    } >> kernel/src/init_blob.S

    echo "${prefix}: build/${prefix}.bin ($SIZE bytes) entry $ENTRY span $SPAN"
}

rm -f kernel/src/init_blob.S
{
    printf '/* SPDX-License-Identifier: Proprietary */\n'
    printf '/* Copyright (c) Faded Dream OS Project. All rights reserved. */\n'
    printf '/* Source is viewable but may not be copied, modified, or redistributed\n   without permission. */\n\n'
    printf '# init_blob.S: generated by scripts/build_init.sh; do not edit.\n'
    printf '# Flat binaries of the user programs, entry at 0x400000.\n\n'
} > kernel/src/init_blob.S

build_one user/init.c init
build_one user/fault_init.c fault_init
