# Source is viewable but may not be copied, modified, or redistributed
# without permission.
#
# Writes kernel/include/build_id.h (git hash, dirty flag, compiler and
# version, build UTC date) so the kernel can print an exact build ID on
# the boot screen: a photo of a black screen or early-failure boot then
# identifies the precise build it came from.
#
# Usage: gen_build_id.sh <compiler-command> [output-header]
# Runs from the repo root. LC_ALL=C everywhere; never fails the build if
# git metadata is absent (prints "unknown" fields instead — e.g. a
# tarball build).

set -u
export LC_ALL=C

CC="${1:-gcc}"
OUT="${2:-kernel/include/build_id.h}"

# git hash (short) + dirty flag; empty if no .git (then 'unknown')
HASH=$(git rev-parse --short HEAD 2>/dev/null || echo unknown)
if [ "$HASH" = "unknown" ]; then
    DIRTY=""
else
    if [ -n "$(git status --porcelain 2>/dev/null | head -1)" ]; then
        DIRTY="-dirty"
    else
        DIRTY=""
    fi
fi
# date: stable UTC stamp of the BUILD (not of the commit)
STAMP=$(date -u +%Y-%m-%dT%H:%MZ)
# compiler name + version: `cc -dumpversion` style, no locale output
CVER=$("$CC" -dumpfullversion -dumpversion 2>/dev/null || \
       "$CC" -dumpversion 2>/dev/null || echo unknown)
CNAME=$(basename "$CC")

# C-string-safe: header embedded with explicit escapes only
cat > "$OUT" <<EOF
/* GENERATED by scripts/gen_build_id.sh — do not edit or commit. */
/* Copyright (c) Faded Dream OS Project. All rights reserved. */
#ifndef VESPER_BUILD_ID_H
#define VESPER_BUILD_ID_H
#define BUILD_ID_GIT     "$HASH$DIRTY"
#define BUILD_ID_CC      "$CNAME $CVER"
#define BUILD_ID_STAMP   "$STAMP"
#endif /* VESPER_BUILD_ID_H */
EOF
echo "build_id: git=$HASH$DIRTY cc=$CNAME $CVER stamp=$STAMP -> $OUT"
